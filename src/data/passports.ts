// Helper function to resolve any passport cleanly
export function findPassport(query: string): PassportRecord | undefined {
  if (!query) return undefined;
  const clean = query.trim();
  return (
    samplePassports[clean] ||
    samplePassports[clean.toUpperCase()] ||
    samplePassports[clean.toLowerCase()] ||
    Object.values(canonicalPassports).find(
      (p) =>
        p.passportId.toLowerCase() === clean.toLowerCase() ||
        p.productId.toLowerCase() === clean.toLowerCase()
    )
  );
}
